"""Daily Trivago hotel prices. Every decision is made by code:

  * stay dates   -> every one-night stay in the flight window + a few 3/7/14-night
                    validation stays, all generated by cohort.py
  * hotel choice -> `discover` searches a few probe stays (1/3/7 nights at an early, a
                    middle and a late check-in, plus an optional --range you care about),
                    keeps only hotels that are really BOOKABLE across them, splits those
                    into low/mid/high by price and freezes, per segment, primary hotels
                    plus similar backup hotels in data/hotel_registry.json (selection.py)
  * daily run    -> `collect` re-prices exactly those hotels (primaries AND backups) for
                    every stay, so a backup already has history when a primary closes
  * guests       -> pilot_hotels.json "guest_scenarios" (adults/rooms). One-night stays are
                    priced for every scenario, validation stays only for 2 adults.

Commands (Windows: use `py` instead of `python`)
    py collect_hotels.py check
    py collect_hotels.py discover --region antalya --headed --dry-run      # look, write nothing
    py collect_hotels.py discover --region antalya --headed
    py collect_hotels.py discover --region antalya --range 2026-10-25:2026-11-01
    py collect_hotels.py discover --region all --force
    py collect_hotels.py collect --headed --limit 3
    py collect_hotels.py collect --kind night --date 2026-10-25   # one night, all guest scenarios
    py collect_hotels.py collect

Safety rules: a price row is written only when the dates AND the guests are confirmed in
the page URL; a missing price stays blank (never 0); a block/captcha stops the run.
"""

