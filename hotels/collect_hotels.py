class AccessBlocked(RuntimeError):
    pass


def load_config():
    return json.loads((ROOT / "pilot_hotels.json").read_text(encoding="utf-8"))


def load_json(path, default):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else default


def save_json(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2), encoding="utf-8")


def csv_value(v):
    if v is None:
        return ""
    if isinstance(v, bool):
        return str(v).lower()
    if isinstance(v, str) and v.lstrip().startswith(("=", "+", "-", "@")):
        return "'" + v
    return v


def append_csv(path, fields, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():  # columns changed since the file was created -> keep the old file aside
        with path.open(encoding="utf-8-sig", newline="") as f:
            header = next(csv.reader(f), [])
        if header != fields:
            backup = path.with_name(path.stem + "_old_" + datetime.now().strftime("%Y%m%d%H%M%S") + ".csv")
            path.rename(backup)
            print("Columns changed; previous file kept as", backup.name)
    new = not path.exists()
    with path.open("a", encoding="utf-8-sig" if new else "utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        if new:
            w.writeheader()
        for row in rows:
            w.writerow({k: csv_value(row.get(k)) for k in fields})


def query_id(cfg, region_id, stay):
    return tv.identifier("|".join([
        "hotel1", region_id, stay["check_in_date"], stay["check_out_date"],
        str(cfg["search_adults"]), str(cfg["search_rooms"]), cfg["currency"]]))


def done_today(day):
    done = set()
    if QUERIES.exists():
        with QUERIES.open(encoding="utf-8-sig", newline="") as f:
            for r in csv.DictReader(f):
                if r["collection_date"] == day and r["query_state"] in ("ok", "partial", "empty"):
                    done.add(r["query_id"])
    return done


def get_template(page, cfg, region):
    cache = load_json(LOCATIONS, {})
    entry = cache.get(region["region_id"])
    if isinstance(entry, dict) and entry.get("search_text") == region["search_text"]:
        return entry["url"]
    url = tv.resolve_region(page, cfg["base_url"], region["search_text"])
    cache[region["region_id"]] = {"search_text": region["search_text"], "url": url}
    save_json(LOCATIONS, cache)
    return url


def new_page(p, headed):
    browser = p.chromium.launch(headless=not headed)
    context = browser.new_context(locale="tr-TR", timezone_id="Europe/Istanbul",
                                  viewport={"width": 1366, "height": 900})
    return browser, context.new_page()


def restart(session):
    """Replace a crashed browser with a fresh one."""
    try:
        session["browser"].close()
    except Exception:
        pass
    session["browser"], session["page"] = new_page(session["p"], session["headed"])


_NOPAGE_LOGGED = set()


def nopage_logger(tag):
    """Keep evidence (once per tag and run) of why paging stopped: screenshot of the page
    bottom + last page text in data/debug/nopage_<tag>_p<pages>.*"""
    def log(page, pages_read):
        if tag in _NOPAGE_LOGGED:
            return
        _NOPAGE_LOGGED.add(tag)
        tv.save_bottom(page, DEBUG / f"nopage_{tag}_p{pages_read}")
        print(f"   note: no 'next page' control after page {pages_read} (see data/debug/nopage_{tag}_p{pages_read}.*)")
    return log


