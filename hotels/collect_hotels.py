def parse_range(text):
    try:
        a, b = text.split(":")
        return requested_stay(a.strip(), b.strip())
    except ValueError as error:
        raise SystemExit(f"--range must look like 2026-10-25:2026-11-01 ({error})")


def probe_once(page, cfg, rid, template, stay, disc):
    method = tv.ensure_dates(page, template, stay)
    if method == "calendar":
        # URL now carries the dates; reload cleanly instead of trusting the half-loaded calendar page
        page.goto(page.url, wait_until="domcontentloaded", timeout=45000)
    page.wait_for_timeout(6000)
    text, records, pages = tv.read_listing(
        page, rid, stay["nights"], max_pages=disc["max_pages"], max_rounds=cfg["max_scroll_rounds"],
        read_all=True, on_no_next=nopage_logger(f"discover_{rid}"))
    return method, text, records, pages


def run_probes(session, cfg, rid, template, probes, disc):
    """Search every probe stay and keep ALL result pages' hotel records."""
    results, last = [], 0.0
    for i, stay in enumerate(probes, 1):
        wait = cfg["minimum_seconds_between_searches"] - (time.monotonic() - last)
        if last and wait > 0:
            time.sleep(wait)
        last = time.monotonic()
        got = None
        for attempt in (1, 2):
            try:
                got = probe_once(session["page"], cfg, rid, template, stay, disc)
                break
            except Exception as error:
                print(f"   [{i}/{len(probes)}] browser error (try {attempt}/2): "
                      f"{type(error).__name__}: {str(error)[:70]}")
                restart(session)
        if not got:
            continue
        method, text, records, pages = got
        page = session["page"]
        if tv.BLOCK_RE.search(text) and not records:
            tv.save_debug(page, DEBUG / f"discover_{rid}_{stay['check_in_date']}_block")
            raise AccessBlocked(f"{rid}: block text and no hotel cards (see data/debug)")
        priced = sum(1 for r in records if r["price_minor"] and r["price_scope"] in selection.OK_SCOPES)
        print(f"   [{i}/{len(probes)}] {stay['check_in_date']} -> {stay['check_out_date']} "
              f"({stay['nights']}n) dates={method or 'UNVERIFIED'} cards={len(records)} "
              f"verified-priced={priced} pages={pages}")
        if not method:
            tv.save_debug(page, DEBUG / f"discover_{rid}_{stay['check_in_date']}_dates")
            if stay.get("kind") == "probe_requested":
                raise RuntimeError("the requested range could not be set on the page, so it cannot be enforced")
            continue
        results.append(dict(stay=stay, required=stay.get("kind") == "probe_requested",
                            records=records, pages_read=pages, dates_method=method))
    return results


def drop_truncated(results, ratio=0.5):
    """Drop a probe that returned far fewer cards than the other probes with the same nights."""
    sizes = {}
    for r in results:
        sizes.setdefault(r["stay"]["nights"], []).append(len(r["records"]))
    kept = []
    for r in results:
        s = sizes[r["stay"]["nights"]]
        if len(s) >= 3 and len(r["records"]) < ratio * statistics.median(s):
            print(f"   dropped truncated probe {r['stay']['check_in_date']} "
                  f"({r['stay']['nights']}n): {len(r['records'])} cards vs median {statistics.median(s):.0f}")
            continue
        kept.append(r)
    return kept


def report_and_save(rid, region, day, results, probes, sel, disc, args, registry):
    need = min(3, len(probes))
    if len(results) < need:
        print(f"{rid}: only {len(results)}/{len(probes)} probe searches had verified dates -> registry not written")
        return
    hotels, profiles, excluded = selection.build_registry(results, sel, disc)
    print(f"\n{rid}: probes {len(results)}/{len(probes)} verified | hotels seen {len(profiles)} | "
          f"eligible {len(profiles) - len(excluded)} | selected {len(hotels)}")
    names = {h["hotel_id"]: h["hotel_name"] for h in hotels}
    for seg in sel["segments"]:
        mine = [h for h in hotels if h["segment"] == seg]
        want = sel["primaries_per_segment"] + sel["backups_per_segment"]
        flag = "" if len(mine) == want else f"   !! only {len(mine)}/{want} hotels available for this segment"
        print(f"  {seg}:{flag}")
        for h in mine:
            tail = f"backup for {names.get(h['backup_for'], '?')}" if h["role"] == "backup" else "primary"
            print(f"    {h['rank']}. {h['hotel_name'][:36]:36} stars={h['stars']} rating={h['rating']} "
                  f"median/night={h['nightly_median']:.0f} coverage={h['coverage']:.2f}  {tail}")
    reasons = Counter("bookable in too few probe searches" if r.startswith("bookable in only") else r
                      for r in excluded.values())
    if reasons:
        print("  left out:", "; ".join(f"{n}x {r}" for r, n in reasons.most_common()))
    by_id = {p["hotel_id"]: p for p in profiles}
    limited = sorted((by_id[i] for i, r in excluded.items() if r in ("not sold for 1 night",)
                      or r.startswith("bookable in only")),
                     key=lambda p: -(p["rating"] or 0))[:8]
    if limited:
        print("  well-rated hotels that are NOT bookable everywhere (smallest stay seen with a price):")
        for p in limited:
            print(f"    {p['hotel_name'][:36]:36} priced for nights={p['priced_nights']} "
                  f"({p['priced']}/{p['n_probes']} searches)")
    save_json(DISCOVERY / f"{rid}_{day.isoformat()}.json", dict(
        region_id=rid, created=day.isoformat(), settings=dict(selection=sel, discovery=disc),
        probes=[dict(**pr["stay"], pages_read=pr["pages_read"], dates_method=pr["dates_method"],
                     cards=len(pr["records"])) for pr in results],
        selected=hotels, excluded=excluded, profiles=profiles))
    if args.dry_run:
        print("  dry run: registry NOT written")
        return
    if not hotels:
        print("  no hotels selected -> registry not written")
        return
    registry[rid] = dict(
        created=day.isoformat(), search_text=region["search_text"],
        probes=[dict(**pr["stay"], pages_read=pr["pages_read"]) for pr in results],
        settings=dict(selection=sel, discovery=disc), hotels=hotels)
    save_json(REGISTRY, registry)
    print("  registry written:", REGISTRY)


def discover(args):
    cfg = load_config()
    day = today()
    registry = load_json(REGISTRY, {})
    regions = [r for r in cfg["regions"] if args.region in ("all", r["region_id"])]
    requested = parse_range(args.range) if args.range else None
    result = 0
    with sync_playwright() as p:
        browser, page = new_page(p, args.headed)
        session = dict(p=p, headed=args.headed, browser=browser, page=page)
        for region in regions:
            rid = region["region_id"]
            if rid in registry and not (args.force or args.dry_run):
                print(rid, "already frozen (use --force to redo)")
                continue
            sel = selection.settings(cfg, region, "selection", selection.SELECTION_DEFAULTS)
            disc = selection.settings(cfg, region, "discovery", selection.DISCOVERY_DEFAULTS)
            probes = ([requested] if requested else []) + probe_stays(day, disc, cfg)
            if args.max_probes:
                probes = probes[: args.max_probes]
            if not probes:
                print(rid, "no probe stays fit the flight window")
                continue
            print(f"{rid}: {len(probes)} discovery searches"
                  + (f", requested range {requested['check_in_date']} -> {requested['check_out_date']}" if requested else ""))
            try:
                template = get_template(session["page"], cfg, region)
                results = run_probes(session, cfg, rid, template, probes, disc)
                results = drop_truncated(results)
                report_and_save(rid, region, day, results, probes, sel, disc, args, registry)
            except AccessBlocked as error:
                print("BLOCKED:", error, "- stopping")
                result = 3
                break
            except Exception as error:
                print(rid, "ERROR", type(error).__name__, str(error)[:300])
                tv.save_debug(session["page"], DEBUG / f"discover_{rid}_error")
                result = result or 2
            time.sleep(8)
        try:
            session["browser"].close()
        except Exception:
            pass
    return result


